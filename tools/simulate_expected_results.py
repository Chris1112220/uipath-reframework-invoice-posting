"""Reference model of the bot's business rules, used to document expected results.

This is NOT the automation. It re-implements the same rules as
Dispatcher/LoadInvoices.xaml and Processing/ValidateInvoice.xaml in plain Python so
the README can show what a run against the sample data should produce, and so the
sample data can be checked without opening UiPath Studio.

    python tools/simulate_expected_results.py   # writes docs/expected-results.md
"""
from __future__ import annotations

from decimal import Decimal
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parents[1]
TOLERANCE_PCT = Decimal("2")
MAX_AUTO_POST = Decimal("25000")
AP_ACCOUNT = "2000-00"


def rows(path: Path, sheet: str) -> list[dict]:
    ws = load_workbook(path, data_only=True)[sheet]
    values = list(ws.iter_rows(values_only=True))
    headers = values[0]
    return [dict(zip(headers, r)) for r in values[1:]]


def is_numeric(value) -> bool:
    try:
        Decimal(str(value))
        return True
    except Exception:
        return False


def validate(inv: dict, vendors: dict, pos: dict) -> tuple[str, str]:
    """Mirror of Processing/ValidateInvoice.xaml. Returns (expense GL, '') or raises ValueError."""
    amount = Decimal(str(inv["Amount"]))
    if amount <= 0:
        raise ValueError(f"Invoice amount must be greater than zero (found {amount:,.2f}).")
    vendor = vendors.get(str(inv["VendorId"] or "").strip().upper())
    if vendor is None:
        raise ValueError(f"Unknown vendor: {inv['VendorId']} is not in the vendor master.")
    if vendor["Status"] != "Active":
        raise ValueError(f"Vendor {inv['VendorId']} ({vendor['VendorName']}) is inactive.")
    po_number = str(inv["PONumber"] or "").strip()
    if not po_number:
        raise ValueError("Missing PO number. Non-PO invoices need manual approval.")
    po = pos.get(po_number.upper())
    if po is None:
        raise ValueError(f"PO {po_number} was not found in the open purchase orders.")
    if po["VendorId"] != vendor["VendorId"]:
        raise ValueError(f"PO {po_number} belongs to vendor {po['VendorId']}, not {inv['VendorId']}.")
    po_amount = Decimal(str(po["POAmount"]))
    received = Decimal(str(po["ReceivedAmount"]))
    variance = abs(amount - po_amount) / po_amount * 100
    if variance > TOLERANCE_PCT:
        raise ValueError(f"Invoice-to-PO variance {variance:.2f}% exceeds the {TOLERANCE_PCT}% tolerance.")
    if amount > received * (1 + TOLERANCE_PCT / 100):
        raise ValueError("3-way match failed: invoice exceeds goods received.")
    if amount > MAX_AUTO_POST:
        raise ValueError("Amount exceeds the auto-post limit; route for manual approval.")
    return vendor["DefaultExpenseGL"], ""


def main() -> None:
    invoices = rows(ROOT / "Data/Input/Invoices.xlsx", "Invoices")
    vendors = {str(v["VendorId"]).upper(): v for v in rows(ROOT / "Data/Input/VendorMaster.xlsx", "Vendors")}
    pos = {str(p["PONumber"]).upper(): p for p in rows(ROOT / "Data/Input/PurchaseOrders.xlsx", "PurchaseOrders")}

    seen: set[str] = set()
    results = []
    journal_lines = 0
    for i, inv in enumerate(invoices, start=2):
        number = str(inv["InvoiceNumber"] or "").strip()
        stage, outcome, detail = "Dispatcher", "", ""
        if not number:
            outcome, detail = "Rejected", "Missing invoice number."
        elif not is_numeric(inv["Amount"]):
            outcome, detail = "Rejected", "Amount is not numeric."
        elif number.upper() in seen:
            outcome, detail = "Duplicate", "Invoice number already seen in this file (not queued)."
        else:
            seen.add(number.upper())
            stage = "Performer"
            try:
                gl, _ = validate(inv, vendors, pos)
                outcome = "Successful"
                detail = f"Posted AP-{number}: Dr {gl} / Cr {AP_ACCOUNT} {Decimal(str(inv['Amount'])):,.2f}"
                journal_lines += 2
            except ValueError as exc:
                outcome, detail = "Business Exception", str(exc)
        results.append((i, number or "(blank)", inv.get("Scenario", ""), stage, outcome, detail))

    counts: dict[str, int] = {}
    for r in results:
        counts[r[4]] = counts.get(r[4], 0) + 1

    lines = [
        "# Expected results for the sample data",
        "",
        "Generated by `tools/simulate_expected_results.py`, a Python model of the same rules the",
        "workflows implement (2% match tolerance, 25,000.00 auto-post limit). Use it to check a",
        "Studio run: the RunReport and JournalEntries files should match this table.",
        "",
        "| Excel row | Invoice | Scenario | Stage | Expected outcome | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | **{r[4]}** | {r[5]} |")
    lines += ["", "**Totals:** " + ", ".join(f"{k}: {v}" for k, v in counts.items())
              + f". Journal lines written: {journal_lines}.", ""]
    out = ROOT / "docs" / "expected-results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
